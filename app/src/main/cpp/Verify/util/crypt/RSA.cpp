    std::vector<unsigned char> RSA::decodeBase64(const std::string &input) {
        BIO *b64 = BIO_new(BIO_f_base64());
        if (!b64) {
            throw std::runtime_error("Failed to create Base64 filter BIO");
        }

        BIO_set_flags(b64, BIO_FLAGS_BASE64_NO_NL);

        BIO *bio_mem = BIO_new_mem_buf(input.c_str(), input.length());
        if (!bio_mem) {
            BIO_free(b64);
            throw std::runtime_error("Failed to create memory buffer BIO");
        }

        BIO *chain = BIO_push(b64, bio_mem);

        std::vector<unsigned char> output(input.size() + 1);

        int len = BIO_read(chain, output.data(), output.size());

        BIO_free_all(chain);

        if (len <= 0) {
            throw std::runtime_error("Base64 decode failed or input was empty");
        }

        output.resize(len);
        return output;
    }

    std::vector<unsigned char> RSA::decrypt(const std::vector<unsigned char> &cipherBytes) {
        OpenSSL_add_all_algorithms();
        ERR_load_crypto_strings();

        const unsigned char *p = privateKeyBytearray.data();

        EVP_PKEY *privKey = d2i_PrivateKey(EVP_PKEY_RSA, nullptr, &p, privateKeyBytearray.size());
        if (!privKey)
            throw std::runtime_error("Failed to load PKCS#8 private key");

        EVP_PKEY_CTX *ctx = EVP_PKEY_CTX_new(privKey, nullptr);
        if (!ctx)
            throw std::runtime_error("EVP_PKEY_CTX_new failed");

        if (EVP_PKEY_decrypt_init(ctx) <= 0)
            throw std::runtime_error("decrypt_init failed");

        if (EVP_PKEY_CTX_set_rsa_padding(ctx, RSA_PKCS1_OAEP_PADDING) <= 0)
            throw std::runtime_error("set padding failed");

        if (EVP_PKEY_CTX_set_rsa_oaep_md(ctx, EVP_sha256()) <= 0)
            throw std::runtime_error("set oaep sha256 failed");

        if (EVP_PKEY_CTX_set_rsa_mgf1_md(ctx, EVP_sha256()) <= 0)
            throw std::runtime_error("set mgf1 sha256 failed");

        size_t outLen = 0;
        if (EVP_PKEY_decrypt(ctx, nullptr, &outLen, cipherBytes.data(), cipherBytes.size()) <= 0)
            throw std::runtime_error("decrypt buffer size failed");

        std::vector<unsigned char> out(outLen);

        if (EVP_PKEY_decrypt(ctx, out.data(), &outLen, cipherBytes.data(), cipherBytes.size()) <= 0)
            throw std::runtime_error("decrypt failed");

        out.resize(outLen);

        EVP_PKEY_free(privKey);
        EVP_PKEY_CTX_free(ctx);

        return out;
    }

    std::string RSA::decryptFromBase64(const std::string &base64Cipher) {
        auto cipher = decodeBase64(base64Cipher);
        auto plain = decrypt(cipher);
        return std::string(plain.begin(), plain.end());
    }

